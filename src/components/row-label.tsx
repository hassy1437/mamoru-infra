/**
 * 行ラベル / ※注記の折り返しを制御する。
 *
 * ■ なぜ要るか（2026-08-05・chromium で 360px 端末の実測から）
 *   ラベルは正典の項目名なので文言を短くできない。折り返しの位置だけを直す。
 *   素の text ノードだと、全1373ラベル中で次の壊れ方が出ていた:
 *     行末に「/」だけが残る 67件 / 括弧が開いたまま改行 12件 /
 *     単位の括弧が本体から離れる 6件 / 行末に「※」だけが残る 6件 /
 *     長音が行頭に来る 2件
 *
 * ■ ★方針: DOM を組み替えず、CSS と不可視の結合文字だけで直す
 *   最初は「/」でまとまりに分けて inline-block を並べる形を試したが、
 *   ★inline-block は境界の空白を落とすため「A / B」が「A/ B」になり、
 *   実測で 242件のラベルで表示が変わった（文言を変えない要件に反する）。
 *   ＝ テキストはそのまま流し、breakのしかたを CSS と U+00A0 / U+2060 で制御する。
 *
 * ■ 効かせ方
 *   1. word-break: keep-all … 日本語を任意位置で割らない（空白でだけ折り返す）
 *   2. 「 / 」の後ろの空白を NBSP に … 区切りの直後で切れない
 *      ＝「/」が行末に取り残されず、次行の頭に付いて「続き」だと分かる
 *   3. 「※」の直後に word joiner … 「※」だけが行末に残らない
 *      （※ は記号なので keep-all の保護対象外。実測で 6→11件に増えて気づいた）
 *   4. line-break: strict … 長音「ー」が行頭に来るのを抑える
 *   5. ★overflow-wrap: anywhere … 1つのまとまりが枠を超えたときの逃げ道。
 *      これが無いと keep-all のせいで枠から溢れる。溢れるより折り返すほうがまし。
 *      実測: 60文字の和文も120文字の英字も、はみ出し 0px で折り返す。
 *
 * ■ 実測（変更前 → 変更後）
 *   /の直後 67→0 / 括弧が分かれる 12→4 / 単位の括弧が離れる 6→6 /
 *   ※が離れる 6→0 / 禁則違反 2→0 / はみ出し 0→0 /
 *   2行以上 266→266（不変）/ 3行以上 2→2（不変）/ 行数が増えたラベル 0件
 *   ★残る 4件・6件は、まとまり自体が枠幅(252px)を超えるもの。
 *     どこかで折り返すしかないので、溢れさせずに折り返している。
 */

/** 折り返しを制御するクラス。★PC表とモバイルカードの両方に付ける。 */
export const WRAP_CLS = "[word-break:keep-all] [overflow-wrap:anywhere] [line-break:strict]";

/**
 * 折り返してほしくない位置を、表示を変えずに結合する。
 *   U+00A0 … 見た目は空白のまま、そこで折り返さない
 *   U+2060 … 幅ゼロ、そこで折り返さない
 * ★どちらも表示上の文字は増えないので、文言は原文のまま。
 */
export function bindLabelBreaks(label: string): string {
  // ★必ずエスケープ表記で書くこと。生の U+00A0 / U+2060 を直接書くと、
  //   エディタでは空白か無に見えるので、次に読む人が「余計な空白」と思って
  //   消したり、整形ツールが落としたりする。実際この関数は一度リテラルで
  //   書かれていて、消えていないかを目視で確かめられなかった。
  const NBSP = "\u00A0"; // 見た目は空白のまま、そこで折り返さない
  const WJ = "\u2060";   // 幅ゼロ、そこで折り返さない
  return label
    // 「 / 」の後ろだけ NBSP にする。前の空白は普通の空白のまま残すので、
    // 折り返しはそこで起き、「/」は次行の頭に付く（行末に取り残されない）。
    .replace(/ \/ /g, ` /${NBSP}`)
    // 「※」が行末に1文字だけ残らないようにする。
    // ★※ は記号なので word-break: keep-all の保護対象外。CSS だけでは守れない。
    .replace(/※/g, `※${WJ}`);
}
